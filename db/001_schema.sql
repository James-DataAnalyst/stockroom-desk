CREATE TABLE warehouses (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code text NOT NULL UNIQUE,
  name text NOT NULL UNIQUE
);

CREATE TABLE customers (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE,
  channel text NOT NULL CHECK (channel IN ('Online', 'Retail', 'Wholesale'))
);

CREATE TABLE products (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku text NOT NULL UNIQUE,
  name text NOT NULL,
  pack text NOT NULL,
  category text NOT NULL,
  unit_price integer NOT NULL CHECK (unit_price > 0),
  reorder_point integer NOT NULL CHECK (reorder_point >= 0)
);

CREATE TABLE inventory (
  warehouse_id integer NOT NULL REFERENCES warehouses(id),
  product_id integer NOT NULL REFERENCES products(id),
  on_hand integer NOT NULL DEFAULT 0 CHECK (on_hand >= 0),
  reserved integer NOT NULL DEFAULT 0 CHECK (reserved >= 0 AND reserved <= on_hand),
  available integer GENERATED ALWAYS AS (on_hand - reserved) STORED,
  PRIMARY KEY (warehouse_id, product_id)
);

CREATE TABLE orders (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id integer NOT NULL REFERENCES customers(id),
  warehouse_id integer NOT NULL REFERENCES warehouses(id),
  status text NOT NULL DEFAULT 'waiting' CHECK (status IN ('waiting', 'reserved', 'dispatched', 'cancelled')),
  channel text NOT NULL CHECK (channel IN ('Online', 'Retail', 'Wholesale')),
  due_on date NOT NULL,
  note text NOT NULL DEFAULT '' CHECK (length(note) <= 240),
  placed_at timestamptz NOT NULL DEFAULT now(),
  reserved_at timestamptz CHECK (reserved_at >= placed_at),
  dispatched_at timestamptz CHECK (dispatched_at >= reserved_at),
  cancelled_at timestamptz CHECK (cancelled_at >= placed_at),
  request_id uuid UNIQUE,
  request_hash text,
  UNIQUE (id, warehouse_id),
  CHECK ((request_id IS NULL) = (request_hash IS NULL)),
  CHECK (status NOT IN ('reserved', 'dispatched') OR reserved_at IS NOT NULL),
  CHECK (status <> 'waiting' OR reserved_at IS NULL),
  CHECK ((status = 'dispatched') = (dispatched_at IS NOT NULL)),
  CHECK ((status = 'cancelled') = (cancelled_at IS NOT NULL))
);
CREATE INDEX orders_recent ON orders (placed_at DESC, id DESC);
CREATE INDEX orders_location_stage ON orders (warehouse_id, status, placed_at DESC, id DESC);
CREATE INDEX orders_open_due ON orders (due_on) WHERE status IN ('waiting', 'reserved');

CREATE TABLE order_items (
  order_id integer NOT NULL REFERENCES orders(id),
  product_id integer NOT NULL REFERENCES products(id),
  quantity integer NOT NULL CHECK (quantity BETWEEN 1 AND 5000),
  unit_price integer NOT NULL CHECK (unit_price > 0),
  PRIMARY KEY (order_id, product_id)
);

CREATE TABLE order_events (
  id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  order_id integer NOT NULL REFERENCES orders(id),
  kind text NOT NULL CHECK (kind IN ('created', 'reserved', 'dispatched', 'cancelled')),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (order_id, kind)
);

CREATE TABLE movements (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  warehouse_id integer NOT NULL,
  product_id integer NOT NULL,
  order_id integer,
  kind text NOT NULL CHECK (kind IN ('opening', 'receipt', 'reserve', 'dispatch', 'release')),
  on_hand_delta integer NOT NULL,
  reserved_delta integer NOT NULL,
  reference text NOT NULL DEFAULT '' CHECK (length(reference) <= 48),
  request_id uuid UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now(),
  FOREIGN KEY (warehouse_id, product_id) REFERENCES inventory(warehouse_id, product_id),
  FOREIGN KEY (order_id, warehouse_id) REFERENCES orders(id, warehouse_id),
  FOREIGN KEY (order_id, product_id) REFERENCES order_items(order_id, product_id),
  UNIQUE (order_id, product_id, kind),
  CHECK ((kind IN ('opening', 'receipt')) = (order_id IS NULL)),
  CHECK ((kind = 'receipt') = (request_id IS NOT NULL)),
  CHECK (
    (kind IN ('opening', 'receipt') AND on_hand_delta > 0 AND reserved_delta = 0) OR
    (kind = 'reserve' AND on_hand_delta = 0 AND reserved_delta > 0) OR
    (kind = 'dispatch' AND on_hand_delta < 0 AND on_hand_delta = reserved_delta) OR
    (kind = 'release' AND on_hand_delta = 0 AND reserved_delta < 0)
  )
);
CREATE INDEX movements_recent ON movements (created_at DESC, id DESC);
CREATE INDEX movements_stock ON movements (warehouse_id, product_id, created_at DESC);

CREATE VIEW stock_levels AS
SELECT w.code AS location_code, w.name AS location, p.sku, p.name AS product, p.category, p.pack,
       i.on_hand, i.reserved, i.available, p.reorder_point,
       i.available <= p.reorder_point AS low_stock
FROM inventory i
JOIN warehouses w ON w.id = i.warehouse_id
JOIN products p ON p.id = i.product_id;
